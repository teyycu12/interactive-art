/**
 * 採水果（籃子接力）的共用設定。
 *
 * ── 這個玩法為什麼長這樣 ──
 * 「走到菜畦旁按一下」是純個人動作：十個人會低頭各採各的，與已經被否決的
 * 普通尋寶是同一種失敗（見 docs/notes/INTERACTION-DESIGN.md 的判準）。
 * 因此規則只有一條，但那一條逼出對話：
 *
 *   **籃子只有一個，而且一個人一輪只能採一畦。**
 *
 * 採完一畦之後，你手上的籃子對你已經沒有用了 —— 要繼續只能把它交出去，
 * 而且得交給一個還沒採過的人。你必須先知道誰還沒採（大螢幕上看得到），
 * 再把那個人叫過來。「欸你過來，換你拿」就是通關路徑上那一步。
 *
 * 放在 shared/ 的理由同 shared/heat.js：伺服器據此判定、大螢幕據此畫範圍、
 * 手機據此顯示到了沒。各寫一份會出現「畫面上明明站在菜畦旁卻採不到」——
 * 現場最惱人的一種故障，因為它看起來像系統壞了而不是規則。
 */
export const HARVEST = {
  /**
   * 走到幾距離內算採到／算送回去。與 `SURVEY.arriveRadius` 同樣是**加在道具
   * 碰撞半徑之外**的量：道具本身是障礙物，角色擠不進 r 以內，實際站位大約在
   * r + 身體半徑。
   *
   * 45 的上限由菜畦間距決定：三畦相距 270，判定圈若超過 (270 - 2×54)/2 = 81
   * 就會重疊，拿著籃子走過中間會莫名其妙採到隔壁那一畦。
   */
  reachRadius: 45,

  /**
   * 接籃子的距離。**下限是 95** —— 那是 `BOIDS.separationRadius`，
   * 兩個自主漫遊的角色實際上擠不進 95 以內。設得比它小的話，
   * 「接過籃子」這個鈕會在沒有人操控的那一側永遠按不下去，
   * 而現場只會看到兩個人站在一起卻交不了東西。
   */
  handRadius: 130,

  /** 完成一輪，每個出過力的人（採過的人與送回去的人）各得這麼多分 */
  points: 60,
};

/**
 * 一輪要採哪幾畦、送回哪裡。都是 `shared/scene.js` 的道具 id ——
 * 碰撞佈局不因主題而異，因此同一組 id 在廚房是菜畦與蔬果籃、
 * 在辦公室是電話亭與零食吧，名稱由各場景的 `ITEMS` 決定。
 * 伺服器只認 id，**不可以在伺服器端出現「菜畦」兩個字**，
 * 否則這個玩法就只能在廚房跑（見 INTERACTION-DESIGN 的場合適配那一條）。
 */
export const HARVEST_PLAN = {
  beds: ['grd_1', 'grd_2', 'grd_3'],
  home: 'k_market',
};
